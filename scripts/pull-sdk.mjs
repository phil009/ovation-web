// Downloads the generated TypeScript SDK from the Ovation API and writes it to src/sdk.
// Usage: pnpm sdk:pull  (reads OVATION_API_URL from .env.local; the server origin, without /api)
//
// Staging sleeps after 15 idle minutes, so the first request can take about a minute:
// a 120 second timeout and one retry.

import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { unzipSync, strFromU8 } from "fflate";

const TIMEOUT_MS = 120_000;
const EXPECTED_FILES = ["schema.ts", "client.ts", "index.ts", "README.md"];
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "src", "sdk");

function fail(message) {
  console.error(`sdk:pull failed: ${message}`);
  process.exit(1);
}

const origin = process.env.OVATION_API_URL?.trim().replace(/\/+$/, "");
if (!origin) fail("OVATION_API_URL is not set. Copy .env.example to .env.local and fill it in.");
if (/\/api$/.test(origin)) fail("OVATION_API_URL must be the server origin, without /api.");

const url = `${origin}/api/sdk/typescript.zip`;

async function download() {
  const response = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!response.ok) throw new Error(`HTTP ${response.status} from ${url}`);
  const disposition = response.headers.get("content-disposition") ?? "";
  const name = /filename="?([^";]+)"?/.exec(disposition)?.[1] ?? "unknown.zip";
  return { name, bytes: new Uint8Array(await response.arrayBuffer()) };
}

let result;
for (let attempt = 1; attempt <= 2; attempt++) {
  try {
    console.log(`Downloading ${url} (attempt ${attempt}; a sleeping server can take a minute)...`);
    result = await download();
    break;
  } catch (error) {
    if (attempt === 2) {
      fail(
        `${error instanceof Error ? error.message : String(error)}. ` +
          "Is the backend running and SDK_DOWNLOAD_ENABLED not false?",
      );
    }
  }
}

let entries;
try {
  entries = unzipSync(result.bytes);
} catch {
  fail("the response was not a valid zip file.");
}

const files = Object.entries(entries).filter(([name]) => !name.endsWith("/"));
const names = files.map(([name]) => path.posix.basename(name));
const missing = EXPECTED_FILES.filter((f) => !names.includes(f));
if (missing.length > 0) fail(`the zip is missing ${missing.join(", ")}.`);

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
for (const [name, data] of files) {
  const base = path.posix.basename(name);
  // Only flat, expected file names: never let a zip entry escape src/sdk.
  if (!/^[\w.-]+$/.test(base)) fail(`unexpected file name in zip: ${name}`);
  const header = base.endsWith(".ts")
    ? "// GENERATED by `pnpm sdk:pull` from the Ovation API. Do not edit by hand.\n"
    : "";
  await writeFile(path.join(outDir, base), header + strFromU8(data), "utf8");
}

const version = /ovation-sdk-(.+)\.zip$/.exec(result.name)?.[1] ?? "unknown";
console.log(`SDK ${version} written to src/sdk (${names.join(", ")}).`);
